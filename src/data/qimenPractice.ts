export interface QimenDraft {
  date: string
  selected: number
  notes: string[]
  joys: string[]
  done: string[]
  before: number | null
  after: number | null
  reflection: string
  updatedAt: number
}
export interface QimenRecord extends QimenDraft {
  id: string
  completedAt: number
  seconds: number
}
export const newQimenDraft = (date: string): QimenDraft => ({ date, selected: 0, notes: QIMEN_GATES.map(() => ''), joys: ['', '', ''], done: [], before: null, after: null, reflection: '', updatedAt: 0 })

export function qimenJournalText(draft: QimenDraft) {
  return [
    `奇门修运 · 六门日课｜${draft.date}｜已实践 ${draft.done.length}/6 门`,
    ...QIMEN_GATES.map((gate, index) => `${draft.done.includes(gate.id) ? '✓ 已实践' : '○ 待实践'} · ${gate.name}\n${draft.notes[index]?.trim() || '未填写心得'}`),
    `日录三吉\n${draft.joys.map((joy, index) => `${index + 1}. ${joy.trim() || '待记录'}`).join('\n')}`,
    `练习前舒适度：${draft.before ?? '未评分'}；练习后：${draft.after ?? '未评分'}（1–5，自我感受）`,
    `收功回看\n${draft.reflection.trim() || '未填写'}`,
    '以日常行动理解修运，不作超自然效力、健康或财富保证。',
  ].join('\n\n')
}
